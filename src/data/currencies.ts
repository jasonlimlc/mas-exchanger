// Helper to generate a realistic 30-day historical series ending today
function generate30DayHistory(baseRate: number, volatility: number = 0.008): { sparkline: number[]; history: CurrencyHistoryPoint[] } {
  const history: CurrencyHistoryPoint[] = [];
  const sparkline: number[] = [];
  
  // Start 30 days ago
  let current = baseRate * (1 - (Math.random() * 0.02 - 0.01));
  const today = new Date('2026-10-15');
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    
    // Slight random walk
    const delta = (Math.sin(i * 0.4) * 0.003 + (Math.random() - 0.49) * volatility) * current;
    current = Math.max(0.0001, current + delta);
    
    // Ensure the last point matches the baseRate closely
    if (i === 0) {
      current = baseRate;
    }
    
    history.push({
      date: dateStr,
      rate: Number(current.toFixed(current > 50 ? 2 : 4)),
    });
    
    if (i < 7) {
      sparkline.push(Number(current.toFixed(current > 50 ? 2 : 4)));
    }
  }
  
  return { sparkline, history };
}

